/* * LED Usage Page (0x08)
 * Formatted for HID_MORPH_6 Macro (Page ID State)
 * Note: &ind prefix removed for macro compatibility
 */

/* --- SET (1) / CLEAR (0) PAIRS --- */

#define P08_NUM      0x08 0x01 1 0x08 0x01 0 // Num Lock
#define P08_CAPS     0x08 0x02 1 0x08 0x02 0 // Caps Lock
#define P08_SCRL     0x08 0x03 1 0x08 0x03 0 // Scroll Lock (v24 ACK)
#define P08_CMP      0x08 0x04 1 0x08 0x04 0 // Compose
#define P08_KANA     0x08 0x05 1 0x08 0x05 0 // Kana
#define P08_PWR      0x08 0x06 1 0x08 0x06 0 // Power
#define P08_SHFT     0x08 0x07 1 0x08 0x07 0 // Shift State
#define P08_DND      0x08 0x08 1 0x08 0x08 0 // Do Not Disturb
#define P08_MUTE     0x08 0x09 1 0x08 0x09 0 // Master Mute
#define P08_TONE     0x08 0x0A 1 0x08 0x0A 0 // Tone Enable
#define P08_HSPD     0x08 0x0B 1 0x08 0x0B 0 // High Speed
#define P08_LSPD     0x08 0x0C 1 0x08 0x0C 0 // Low Speed
#define P08_BLOW     0x08 0x11 1 0x08 0x11 0 // Battery Low
#define P08_BOK      0x08 0x12 1 0x08 0x12 0 // Battery OK
#define P08_BCHG     0x08 0x13 1 0x08 0x13 0 // Battery Charging
#define P08_MSGL     0x08 0x1E 1 0x08 0x1E 0 // Message Waiting
#define P08_NIT      0x08 0x21 1 0x08 0x21 0 // Night Mode
#define P08_GEN      0x08 0x3B 1 0x08 0x3B 0 // Generic (v25 DFS)
#define P08_EXTP     0x08 0x4A 1 0x08 0x4A 0 // External Power
#define P08_FWD      0x08 0x4B 1 0x08 0x4B 0 // Media Forward
#define P08_REV      0x08 0x4C 1 0x08 0x4C 0 // Media Reverse
#define P08_STOP     0x08 0x4D 1 0x08 0x4D 0 // Media Stop
#define P08_PAUS     0x08 0x4E 1 0x08 0x4E 0 // Media Pause
